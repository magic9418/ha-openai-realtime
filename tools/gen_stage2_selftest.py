#!/usr/bin/env python3
"""Generate the stage-2 boot self-test expectations (and verify the vector generators agree).

The firmware (esphome/components/micro_wake_word/wake_stage2_selftest.h) builds three synthetic int8
inputs [1,100,40,1] in code: constant -128, a sawtooth ((i%32)*8-128) and a fixed LCG pattern ((top byte>>2)-90). This script builds
the same vectors, runs the .tflite with the reference LiteRT interpreter and writes the expected int8
outputs to esphome/components/micro_wake_word/wake_stage2_expected.h. The device accepts +-2.

  python tools/gen_stage2_selftest.py [--model wake_words/penny_stage2_v1.tflite] [--write] [--check]

--check prints FNV-1a-32 of each vector; tests/test_wake_stage2.cpp prints the same from the C++ generator.
Needs numpy and ai_edge_litert (or tflite_runtime / tensorflow) - e.g. the venv-mww used for the wake work.
"""
import argparse
import pathlib
import sys

import numpy as np

N = 100 * 40


def vector(k: int) -> np.ndarray:
    out = np.zeros(N, dtype=np.int8)
    x = 12345
    for i in range(N):
        v = -128
        if k == 1:
            v = (i % 32) * 8 - 128
        elif k == 2:
            x = (x * 1664525 + 1013904223) & 0xFFFFFFFF
            v = ((x >> 24) >> 2) - 90
        out[i] = v
    return out


def fnv1a(a: np.ndarray) -> int:
    h = 0x811C9DC5
    for b in a.astype(np.int8).tobytes():
        h = ((h ^ b) * 0x01000193) & 0xFFFFFFFF
    return h


def interpreter(model: str):
    try:
        from ai_edge_litert.interpreter import Interpreter
    except ImportError:
        try:
            from tflite_runtime.interpreter import Interpreter
        except ImportError:
            from tensorflow.lite.python.interpreter import Interpreter
    it = Interpreter(model_path=model)
    it.allocate_tensors()
    return it


def main() -> int:
    repo = pathlib.Path(__file__).resolve().parent.parent
    # satellite1: files at the repo root; voice-pe: under home-assistant-voice-pe/
    here = repo / "home-assistant-voice-pe" if (repo / "home-assistant-voice-pe").is_dir() else repo
    ap = argparse.ArgumentParser()
    ap.add_argument("--model", default=str(here / "wake_words" / "penny_stage2_v1.tflite"))
    ap.add_argument("--write", action="store_true", help="rewrite wake_stage2_expected.h")
    ap.add_argument("--check", action="store_true", help="print vector hashes")
    args = ap.parse_args()
    it = interpreter(args.model)
    inp = it.get_input_details()[0]
    out = it.get_output_details()[0]
    assert inp["dtype"] == np.int8 and list(inp["shape"]) == [1, 100, 40, 1], inp
    got = []
    for k in range(3):
        v = vector(k)
        it.set_tensor(inp["index"], v.reshape(1, 100, 40, 1))
        it.invoke()
        got.append(int(it.get_tensor(out["index"])[0][0]))
        if args.check:
            print(f"vector {k}: fnv1a32 0x{fnv1a(v):08x}")
    print("expected int8 outputs:", got, "-> scores 0-255:", [g + 128 for g in got])
    if args.write:
        dest = here / "esphome" / "components" / "micro_wake_word" / "wake_stage2_expected.h"
        dest.write_text(
            "#pragma once\n"
            "// GENERATED by tools/gen_stage2_selftest.py from penny_stage2_v1.tflite (reference LiteRT kernels).\n"
            "// int8 model outputs for the 3 synthetic vectors of wake_stage2_selftest.h. Device tolerance +-2.\n"
            "#include <cstdint>\n"
            "namespace esphome::micro_wake_word {\n"
            f"constexpr int8_t STAGE2_SELFTEST_EXPECTED[3] = {{{got[0]}, {got[1]}, {got[2]}}};\n"
            "}  // namespace esphome::micro_wake_word\n"
        )
        print("wrote", dest)
    return 0


if __name__ == "__main__":
    sys.exit(main())
